#!/usr/bin/env python3
"""Editor-neutral UML generation. See docs/guides/03-diagrams.md#diagram-authoring-and-markdown-preview for the contract."""

import argparse
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile
import uuid
import xml.etree.ElementTree as ET

MARKER = b"<!-- Generated by scripts/diagrams.py; edit the adjacent .puml. -->\n"
REPAIR = "Run python3 scripts/diagrams.py render, then stage sources and SVGs."
KINDS = {"usecase", "component", "package", "class", "sequence", "state"}


class DiagramError(Exception):
    """A failed validation must never publish or stage partial output."""


def run(args, **kwargs):
    try:
        result = subprocess.run(args, stdout=subprocess.PIPE, stderr=subprocess.PIPE, **kwargs)
    except OSError as exc:
        raise DiagramError(f"Cannot run {args[0]}: {exc}. See docs/guides/03-diagrams.md#diagram-authoring-and-markdown-preview") from exc
    if result.returncode:
        message = result.stderr.decode(errors="replace") or result.stdout.decode(errors="replace")
        raise DiagramError(f"{args[0]} failed ({result.returncode}): {message.strip()}")
    return result.stdout


def regular(root, path):
    full = root / path
    if not full.is_file() or full.is_symlink() or not full.resolve().is_relative_to(root.resolve()):
        raise DiagramError(f"Expected a regular file inside the repository: {path}")
    return full


def inputs(root):
    sources = sorted(p.relative_to(root) for p in (root / "docs").rglob("*.puml"))
    includes = sorted(p.relative_to(root) for p in (root / "docs").rglob("*.iuml"))
    outputs = [p.with_suffix(".svg") for p in sources]
    if len({str(p).casefold() for p in outputs}) != len(outputs):
        raise DiagramError("Conflicting diagram output names (including case-only differences)")
    for path in sources + includes:
        text = regular(root, path).read_text(encoding="utf-8")
        if path in sources:
            if len(re.findall(r"(?m)^@startuml$", text)) != 1 or len(re.findall(r"(?m)^@enduml$", text)) != 1:
                raise DiagramError(f"{path}: require one unnamed @startuml / @enduml pair")
            if len(re.findall(r"(?m)^@(?:start|end)\w+", text)) != 2:
                raise DiagramError(f"{path}: multiple/named diagram outputs are forbidden")
            kind = re.search(r"(?m)^' diagram-type: (\w+)$", text)
            if not kind or kind[1] not in KINDS:
                raise DiagramError(f"{path}: declare an approved UML diagram-type: {sorted(KINDS)}")
            if re.search(r"(?mi)^\s*(?:start|stop|activity|partition|fork|@start(?:json|yaml|mindmap))\b", text):
                raise DiagramError(f"{path}: activity/data/flowchart notation is outside the approved UML views")
        elif re.search(r"(?m)^\s*@(?:start|end)", text):
            raise DiagramError(f"{path}: includes cannot declare diagrams")
        for line in text.splitlines():
            if line.lstrip().startswith("!"):
                match = re.fullmatch(r"!include ([^\r\n]+)", line)
                if not match:
                    raise DiagramError(f"{path}: only local !include directives are allowed")
                target = (root / path.parent / match[1]).resolve()
                if not target.is_relative_to((root / "docs").resolve()) or target.suffix != ".iuml":
                    raise DiagramError(f"{path}: include must be a local docs/*.iuml: {match[1]}")
                regular(root, target.relative_to(root.resolve()))
            if "%" in line or re.search(r"<img:|https?://|file://", line, re.I):
                raise DiagramError(f"{path}: external assets and preprocessor functions are forbidden")
    # Explicit cycle detection avoids a renderer-dependent recursion failure.
    def visit(path, stack):
        if path in stack:
            raise DiagramError(f"Cyclic diagram include: {path}")
        text = (root / path).read_text(encoding="utf-8")
        for target in re.findall(r"(?m)^!include (.+)$", text):
            child = (root / path.parent / target).resolve().relative_to(root.resolve())
            visit(child, stack | {path})
    for path in sources + includes:
        visit(path, set())
    return sources, includes


def owned(root):
    """The marker makes ownership explicit; other SVGs are never garbage-collected."""
    return {p.relative_to(root) for p in (root / "docs").rglob("*.svg")
            if regular(root, p.relative_to(root)).read_bytes().startswith(MARKER)}


def configuration(root):
    config = {}
    for line in (root / "scripts/diagrams.lock").read_text().splitlines():
        if line and not line.startswith("#"):
            key, sep, value = line.partition("=")
            if not sep or key in config:
                raise DiagramError("Invalid scripts/diagrams.lock")
            config[key] = value
    if set(config) != {"image", "platform"} or config["platform"] != "linux/amd64":
        raise DiagramError("Renderer lock must specify image and linux/amd64 platform")
    if not re.fullmatch(r"plantuml/plantuml@sha256:[0-9a-f]{64}", config["image"]):
        raise DiagramError("Renderer image must use an immutable official PlantUML digest")
    return config


def render_all(root):
    sources, includes = inputs(root)
    if not sources:
        return {}
    config = configuration(root)
    with tempfile.TemporaryDirectory(prefix="diagram-render-") as directory:
        scratch = Path(directory).resolve()
        for path in sources + includes:
            (scratch / path).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(root / path, scratch / path)
        container = "bugreport-diagrams-" + uuid.uuid4().hex
        args = ["docker", "run", "--rm", "--name", container, "--pull=never", "--platform", config["platform"],
                "--network=none", "--read-only", "--tmpfs", "/tmp:rw,size=128m",
                "--user", f"{os.getuid()}:{os.getgid()}", "--env", "TZ=UTC",
                "--env", "JAVA_TOOL_OPTIONS=-Djdk.lang.Process.launchMechanism=fork",
                "--env", "LANG=C.UTF-8", "--env", "PLANTUML_SECURITY_PROFILE=SANDBOX",
                "--volume", f"{scratch}:/work", "--workdir", "/work", config["image"],
                "-tsvg", "-nometadata", "-charset", "UTF-8", "-failfast2", "-nbthread", "1"]
        # Resolve local includes ourselves: SANDBOX blocks all file/network reads in PlantUML.
        def expand(path):
            text = (root / path).read_text(encoding="utf-8")
            def include(match):
                child = (root / path.parent / match[1]).resolve().relative_to(root.resolve())
                return expand(child)
            return re.sub(r"(?m)^!include (.+)$", include, text)
        for path in sources:
            (scratch / path).write_text(expand(path), encoding="utf-8")
        try:
            run(args + [str(p) for p in sources], timeout=180)
        except DiagramError as exc:
            raise DiagramError(f"{exc}\nFix the staged source or run python3 scripts/diagrams.py pull "
                               "for a missing image; see docs/guides/03-diagrams.md#diagram-authoring-and-markdown-preview.") from exc
        except subprocess.TimeoutExpired as exc:
            raise DiagramError("Diagram rendering timed out; no output published") from exc
        finally:
            # Killing a Docker client on timeout does not necessarily stop its container.
            try:
                subprocess.run(["docker", "rm", "--force", container], stdout=subprocess.DEVNULL,
                               stderr=subprocess.DEVNULL, timeout=10, check=False)
            except (OSError, subprocess.TimeoutExpired):
                pass
        generated = {}
        for path in sources:
            output = path.with_suffix(".svg")
            try:
                data = (scratch / output).read_bytes()
                svg = ET.fromstring(data)
            except (OSError, ET.ParseError) as exc:
                raise DiagramError(f"{path}: missing or invalid SVG: {exc}") from exc
            if svg.tag != "{http://www.w3.org/2000/svg}svg" or "Syntax Error" in "".join(svg.itertext()):
                raise DiagramError(f"{path}: renderer returned an error image")
            # Editors may lack the renderer's font. Keep its metrics but provide a CSS fallback.
            data = data.replace(b'font-family="\'DejaVu Sans\'"', b'font-family="DejaVu Sans,sans-serif"')
            generated[output] = MARKER + data.rstrip() + b"\n"
        actual = {p.relative_to(scratch) for p in scratch.rglob("*.svg")}
        if actual != set(generated):
            raise DiagramError(f"Unexpected renderer outputs: {actual ^ set(generated)}")
        return generated


def validate_links(root, sources, require_outputs=True):
    """Validate diagram notation and navigation without depending on editor extensions."""
    embedded, linked = set(), set()
    expected = {p.with_suffix(".svg") for p in sources}
    for page in (root / "docs").rglob("*.md"):
        text = page.read_text(encoding="utf-8")
        if re.search(r"(?m)^\s*```(?:mermaid|plantuml|puml)\b", text):
            raise DiagramError(f"{page.relative_to(root)}: use separate .puml / SVG or allocation tables")
        for match in re.finditer(r"(!?)\[([^\]]*)\]\(([^)]+)\)", text):
            image, alt, destination = match.groups()
            destination = destination.strip("<>").split("#", 1)[0]
            if not destination.endswith((".svg", ".puml", ".iuml")):
                continue
            target = (page.parent / destination).resolve()
            if not target.is_relative_to(root.resolve()):
                raise DiagramError(f"{page}: diagram link escapes repository: {destination}")
            path = target.relative_to(root.resolve())
            if require_outputs or target.suffix != ".svg" or path not in expected:
                regular(root, path)
            if image:
                if not alt.strip():
                    raise DiagramError(f"{page}: diagram image needs descriptive alt text")
                embedded.add(path)
            else:
                linked.add(path)
    for source in sources:
        if source not in linked or source.with_suffix(".svg") not in embedded:
            raise DiagramError(f"{source}: needs a Markdown SVG embed and editable source link")


def changes(root, generated):
    stale = [path for path, data in generated.items()
             if not (root / path).exists() or regular(root, path).read_bytes() != data]
    orphaned = owned(root) - set(generated)
    return sorted(stale), sorted(orphaned)


def publish(root, generated):
    stale, orphaned = changes(root, generated)
    # Validate the entire batch before any writes. Unmarked files are never overwritten.
    for path in stale:
        if (root / path).exists() and path not in owned(root):
            raise DiagramError(f"{path}: output collides with an unrelated SVG; move it first")
    for path in stale:
        with tempfile.NamedTemporaryFile(dir=(root / path).parent, delete=False) as handle:
            handle.write(generated[path])
            temporary = Path(handle.name)
        temporary.chmod(0o644)
        os.replace(temporary, root / path)
    for path in orphaned:
        (root / path).unlink()
    print(f"Rendered {len(generated)} diagrams; updated {len(stale)}, removed {len(orphaned)} owned SVGs.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=["render", "check", "hook", "setup", "uninstall", "pull", "_snapshot"])
    args = parser.parse_args()
    root = (Path.cwd().resolve() if args.mode == "_snapshot" else
            Path(run(["git", "rev-parse", "--show-toplevel"]).decode().strip()).resolve())
    if args.mode in {"hook", "setup", "uninstall"}:
        from diagram_git import hook, setup
        if args.mode == "hook":
            hook(root)
        else:
            setup(root, uninstall=args.mode == "uninstall")
        return
    if args.mode == "pull":
        config = configuration(root)
        run(["docker", "pull", "--platform", config["platform"], config["image"]])
        print("Pinned renderer downloaded.")
        return
    sources, _ = inputs(root)
    validate_links(root, sources, require_outputs=False)
    generated = render_all(root)
    if args.mode == "check":
        stale, orphaned = changes(root, generated)
        if stale or orphaned:
            raise DiagramError("\n".join([*(f"Stale or missing: {p}" for p in stale),
                                           *(f"Orphaned: {p}" for p in orphaned), REPAIR]))
        validate_links(root, sources)
        print(f"Fresh: {len(generated)} SVGs; diagram links and notation valid.")
    else:
        publish(root, generated)
        validate_links(root, sources)


if __name__ == "__main__":
    # The hook helper imports these contracts; keep one exception class when run as a script.
    sys.modules.setdefault("diagrams", sys.modules[__name__])
    try:
        main()
    except (DiagramError, OSError, UnicodeError) as exc:
        print(f"diagrams: {exc}", file=sys.stderr)
        sys.exit(1)
